import 'dotenv/config';
import assert from 'node:assert/strict';
import { createHmac, randomUUID } from 'node:crypto';
import { createPostgresClient, closePostgresPools } from '../src/mastra/db/postgres';
const original = process.env.DATABASE_URL!;
const maintenance = createPostgresClient();
const database = 'vioscope_sessions_' + randomUUID().replaceAll('-', '');
await maintenance.pool.query(`CREATE DATABASE "${database}"`);
try {
  const url = new URL(original); url.pathname = '/' + database;
  process.env.DATABASE_URL = url.toString(); process.env.AUTH_SECRET = randomUUID();
  const users = await import('../src/mastra/db/users');
  const auth = await import('../src/mastra/auth/session');
  const me = await import('../app/api/auth/me/route');
  const change = await import('../app/api/auth/change-password/route');
  await users.ensureUsersTable();
  const seed = { username: 'session.test', displayName: 'Synthetic session test', email: 'sessions@example.test', role: 'member' as const, password: 'InitialPass1!', passwordResetRequired: false };
  await users.upsertLocalUser(seed);
  let user = (await users.getUserByUsername(seed.username))!;
  const token = () => auth.createSessionToken(user);
  const request = (value: string) => new Request('http://localhost/api/auth/me', { headers: { cookie: auth.sessionCookieName + '=' + value } });
  const status = async (value: string) => (await me.GET(request(value))).status;
  const originalToken = token(); assert.equal(await status(originalToken), 200);
  user = await users.updateOwnUserProfile({ userId: user.id, displayName: 'Updated profile' });
  assert.equal(await status(originalToken), 200, 'Profile edits must not revoke sessions.');
  const response = await change.POST(new Request('http://localhost/api/auth/change-password', { method: 'POST', headers: { cookie: auth.sessionCookieName + '=' + originalToken, 'content-type': 'application/json' }, body: JSON.stringify({ currentPassword: seed.password, newPassword: 'SecondPass2!' }) }));
  assert.equal(response.status, 200);
  const renewed = response.headers.get('set-cookie')!.split(';')[0]!.split('=')[1]!;
  assert.equal(await status(originalToken), 401, 'Old sessions expire immediately, without a clock-based grace period.');
  assert.equal(await status(renewed), 200, 'Password-change response issues a usable new cookie.');
  user = (await users.getUserByUsername(seed.username))!;
  const beforeReset = token();
  user = await users.updateUserByAdmin({ userId: user.id, actorRole: 'administrator', temporaryPassword: 'TemporaryPass3!' });
  assert.equal(await status(beforeReset), 401);
  const firstTemporaryToken = token();
  user = await users.updateUserByAdmin({ userId: user.id, actorRole: 'administrator', temporaryPassword: 'TemporaryPass4!' });
  assert.equal(await status(firstTemporaryToken), 401, 'Repeated resets revoke sessions even when passwordChangedAt stays null.');
  user = await users.changeLocalUserPassword(user.id, 'TemporaryPass4!', 'RecoveredPass5!');
  const beforeRecovery = token();
  const reset = await users.requestPasswordReset(seed.username); assert.ok(reset);
  assert.equal(await status(beforeRecovery), 200, 'An unauthenticated reset request alone must not log users out.');
  user = (await users.authenticateLocalUser(seed.username, reset.temporaryPassword))!; assert.ok(user);
  assert.equal(await status(beforeRecovery), 401, 'Consuming recovery credentials revokes previous sessions.');
  const recoveryToken = token(); assert.equal(await status(recoveryToken), 200);
  user = await users.changeLocalUserPassword(user.id, reset.temporaryPassword, 'FinalPass6!');
  assert.equal(await status(recoveryToken), 401);
  const supersededRecovery = await users.requestPasswordReset(seed.username); assert.ok(supersededRecovery);
  user = await users.updateUserByAdmin({ userId: user.id, actorRole: 'administrator', temporaryPassword: 'AdminOverride6!' });
  assert.equal(await users.authenticateLocalUser(seed.username, supersededRecovery.temporaryPassword), null, 'Admin reset invalidates previously issued recovery codes.');
  user = await users.changeLocalUserPassword(user.id, 'AdminOverride6!', 'FinalPass6!');
  const beforeDisable = token();
  await users.updateUserByAdmin({ userId: user.id, actorRole: 'administrator', provisioningStatus: 'disabled' });
  user = await users.updateUserByAdmin({ userId: user.id, actorRole: 'administrator', provisioningStatus: 'active' });
  assert.equal(await status(beforeDisable), 401, 'Re-enabling an account must not resurrect its old sessions.');
  const beforeSeed = token(); await users.upsertLocalUser({ ...seed, password: 'SeededPass7!' });
  assert.equal(await status(beforeSeed), 401, 'CLI credential replacement also revokes sessions.');
  user = (await users.getUserByUsername(seed.username))!;
  const concurrent = await Promise.allSettled([users.changeLocalUserPassword(user.id, 'SeededPass7!', 'ConcurrentPass8!'), users.changeLocalUserPassword(user.id, 'SeededPass7!', 'ConcurrentPass9!')]);
  assert.equal(concurrent.filter(result => result.status === 'fulfilled').length, 1, 'Only one concurrent change may consume a credential version.');
  const legacy = Buffer.from(JSON.stringify({ sub: user.id, iat: Math.floor(Date.now()/1000), exp: Math.floor(Date.now()/1000)+3600 })).toString('base64url');
  assert.equal(auth.verifySessionToken(legacy + '.' + createHmac('sha256', process.env.AUTH_SECRET).update(legacy).digest('base64url')), null, 'Pre-upgrade cookies require a fresh login.');
  console.log('Session revocation passed: profile preservation, password-change cookie, admin/repeated resets, recovery, disable/re-enable, CLI replacement, concurrent changes and legacy-cookie rejection.');
} finally {
  await closePostgresPools(process.env.DATABASE_URL);
  await maintenance.pool.query(`DROP DATABASE "${database}"`);
  await closePostgresPools(original);
}
